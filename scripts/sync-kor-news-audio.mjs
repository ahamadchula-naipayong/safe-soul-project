/**
 * Sync all KOR*.mp3 audio files from local Deepdive audio/done folder to Cloudflare R2
 * and generate src/lib/korNewsAudioMap.ts for instant 1-to-1 news audio matching.
 */
import fs from 'fs';
import path from 'path';
import { exec } from 'child_process';
import { promisify } from 'util';

const execAsync = promisify(exec);

const SOURCE_DIR = 'C:\\Users\\n_aha\\Desktop\\AGY space\\AGY output\\Deepdive audio\\done';
const R2_BUCKET = 'fitrah-shield-media';
const R2_PUBLIC_BASE = 'https://pub-f97e75c998b047ada96253d539c8f805.r2.dev';
const MAP_OUT_PATH = path.join(process.cwd(), 'src', 'lib', 'korNewsAudioMap.ts');

// Load .env.local
const envPath = path.join(process.cwd(), '.env.local');
if (fs.existsSync(envPath)) {
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const idx = line.indexOf('=');
    if (idx > 0 && !line.trim().startsWith('#')) {
      const k = line.slice(0, idx).trim();
      const v = line.slice(idx + 1).trim().replace(/^['"]|['"]$/g, '');
      if (!process.env[k]) process.env[k] = v;
    }
  }
}

async function uploadFile(fileName, fullPath) {
  const objectKey = `audio/news/${fileName}`;
  const accountId = process.env.CLOUDFLARE_ACCOUNT_ID || '2e1b9f31899de83cd61c91278688516c';
  const apiToken = process.env.CLOUDFLARE_API_TOKEN;

  // Fast path: direct Cloudflare R2 REST API upload
  if (apiToken) {
    const buf = fs.readFileSync(fullPath);
    const res = await fetch(
      `https://api.cloudflare.com/client/v4/accounts/${accountId}/r2/buckets/${R2_BUCKET}/objects/${encodeURIComponent(objectKey)}`,
      {
        method: 'PUT',
        headers: {
          Authorization: `Bearer ${apiToken}`,
          'Content-Type': 'audio/mpeg',
        },
        body: buf,
      }
    );
    if (res.ok) {
      return `${R2_PUBLIC_BASE}/${objectKey}`;
    }
  }

  // Fallback: quoted wrangler CLI
  await execAsync(
    `npx wrangler r2 object put "${R2_BUCKET}/${objectKey}" --file "${fullPath}" --content-type "audio/mpeg" --remote`,
    {
      env: {
        ...process.env,
        CLOUDFLARE_ACCOUNT_ID: accountId,
      },
      maxBuffer: 10 * 1024 * 1024,
    }
  );
  return `${R2_PUBLIC_BASE}/${objectKey}`;
}

async function main() {
  if (!fs.existsSync(SOURCE_DIR)) {
    throw new Error(`Source directory not found: ${SOURCE_DIR}`);
  }

  const files = fs
    .readdirSync(SOURCE_DIR)
    .filter((f) => /^KOR.+\.mp3$/i.test(f))
    .sort();

  console.log(`Found ${files.length} KOR*.mp3 files in ${SOURCE_DIR}`);

  const audioMap = {};
  const CONCURRENCY = 5;
  let completed = 0;

  for (let i = 0; i < files.length; i += CONCURRENCY) {
    const batch = files.slice(i, i + CONCURRENCY);
    await Promise.all(
      batch.map(async (fileName) => {
        const fullPath = path.join(SOURCE_DIR, fileName);
        const url = await uploadFile(fileName, fullPath);
        const codeKey = fileName.replace(/\.mp3$/i, '').trim().toLowerCase();
        audioMap[codeKey] = url;
        completed++;
        console.log(`[${completed}/${files.length}] Uploaded ${fileName}`);
      })
    );
  }

  // Generate TypeScript map sorted by key
  const sortedEntries = Object.entries(audioMap).sort(([a], [b]) => a.localeCompare(b));
  const tsLines = [
    '// Auto-generated by scripts/sync-kor-news-audio.mjs',
    '// Maps lowercase KOR news code (e.g. "kor2611461") -> Cloudflare R2 MP3 URL',
    '',
    'export const KOR_NEWS_AUDIO_MAP: Record<string, string> = {',
    ...sortedEntries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
    '};',
    '',
    'export function getKorNewsAudioUrl(korNoOrSlug?: string | null): string | undefined {',
    '  if (!korNoOrSlug) return undefined;',
    '  const normalized = String(korNoOrSlug).trim().toLowerCase();',
    '  if (KOR_NEWS_AUDIO_MAP[normalized]) return KOR_NEWS_AUDIO_MAP[normalized];',
    '  const match = normalized.match(/kor[a-z0-9]+/i);',
    '  if (match && KOR_NEWS_AUDIO_MAP[match[0].toLowerCase()]) {',
    '    return KOR_NEWS_AUDIO_MAP[match[0].toLowerCase()];',
    '  }',
    '  return undefined;',
    '}',
    '',
  ];

  fs.writeFileSync(MAP_OUT_PATH, tsLines.join('\n'), 'utf8');
  console.log(`✅ Wrote ${sortedEntries.length} KOR audio entries to ${MAP_OUT_PATH}`);
}

main().catch((err) => {
  console.error('❌ Sync failed:', err);
  process.exit(1);
});
